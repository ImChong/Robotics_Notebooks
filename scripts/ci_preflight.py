#!/usr/bin/env python3
"""Run the local preflight sequence used to avoid GitHub Actions drift.

The repository has several derived outputs: JSON exports, search index, graph
exports and home stats. Running only part of the chain is the common cause of
Actions failures, so this script keeps the order in one place.

All outputs written here are gitignored (regenerated by pages.yml at deploy time),
so preflight never dirties tracked files and PRs never carry derived data that
conflicts with main. catalog.md and log.md are bot-owned: export.yml updates them
on main (see scripts/pr_derived_guard.py).
"""

from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
import tempfile
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent

# preflight 不应改动的入库路径：派生产物全部 gitignore（pages.yml 部署时生成），
# catalog.md / log.md 只由 main 上的 export.yml 更新
GENERATED_PATHS = [
    "catalog.md",
    "log.md",
    "README.md",
    "docs/index.html",
    "docs/sw.js",
    "docs/exports",
    "exports",
]


def run(cmd: list[str], description: str) -> None:
    print(f"\n==> {description}", flush=True)
    print("$ " + " ".join(cmd), flush=True)
    subprocess.run(cmd, cwd=REPO_ROOT, check=True)


def check_generated_clean() -> None:
    result = subprocess.run(
        ["git", "diff", "--name-only", "HEAD", "--", *GENERATED_PATHS],
        cwd=REPO_ROOT,
        check=True,
        capture_output=True,
        text=True,
    )
    changed = [line for line in result.stdout.splitlines() if line.strip()]
    if not changed:
        print("\n==> Generated outputs are already committed", flush=True)
        return

    print(
        "\nPreflight modified tracked files (derived outputs must stay gitignored / bot-owned):",
        flush=True,
    )
    for path in changed:
        print(f"- {path}", flush=True)
    sys.exit(1)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Regenerate exports/stats and run the same quality gates as CI."
    )
    parser.add_argument(
        "--check-generated-clean",
        action="store_true",
        help="fail if generated outputs differ from the working tree after regeneration",
    )
    parser.add_argument(
        "--skip-quality",
        action="store_true",
        help="only regenerate derived outputs; skip lint/search/export quality checks",
    )
    return parser.parse_args()


def _default_diff_base() -> str:
    """分支已有提交相对 origin/main 偏离时用 origin/main，否则回退 HEAD。"""
    try:
        subprocess.run(
            ["git", "rev-parse", "--verify", "origin/main"],
            cwd=REPO_ROOT,
            check=True,
            capture_output=True,
            text=True,
        )
        head_sha = subprocess.run(
            ["git", "rev-parse", "HEAD"],
            cwd=REPO_ROOT,
            check=True,
            capture_output=True,
            text=True,
        ).stdout.strip()
        merge_base = subprocess.run(
            ["git", "merge-base", "HEAD", "origin/main"],
            cwd=REPO_ROOT,
            check=True,
            capture_output=True,
            text=True,
        ).stdout.strip()
        if merge_base and merge_base != head_sha:
            return "origin/main"
    except (subprocess.SubprocessError, OSError):
        pass
    return "HEAD"


def _needs_npm_ci() -> bool:
    lock_file = REPO_ROOT / "package-lock.json"
    if not lock_file.is_file():
        return False
    if os.environ.get("CI") == "true":
        return True
    mermaid_pkg = REPO_ROOT / "node_modules" / "mermaid" / "package.json"
    if not mermaid_pkg.is_file():
        return True
    node_modules = REPO_ROOT / "node_modules"
    return lock_file.stat().st_mtime > node_modules.stat().st_mtime


def main() -> None:
    args = parse_args()

    if not args.skip_quality:
        run(
            [sys.executable, "scripts/check_project_nodes.py", "--base", _default_diff_base()],
            "Check project identities and newly added entity metadata",
        )

    run(
        [sys.executable, "scripts/export_minimal.py"],
        "Export wiki JSON, sitemap, and search index",
    )
    if (REPO_ROOT / "package-lock.json").is_file():
        if _needs_npm_ci():
            run(["npm", "ci"], "Install Node dependencies (ESLint)")
        if not args.skip_quality:
            run(["npm", "run", "lint:mermaid"], "Validate all published Mermaid diagrams")

    run([sys.executable, "scripts/generate_link_graph.py"], "Update link graph and graph-stats")

    lint_results = None
    coverage_json: Path | None = None
    try:
        if not args.skip_quality:
            # 单次 lint：home-stats 与 lint-report 共用结果，避免 generate_home_stats 内二次全库扫描。
            import lint_wiki

            print("\n==> Run wiki lint (once, shared with home-stats)", flush=True)
            lint_results = lint_wiki.lint()
            coverage = lint_wiki.coverage_stats(lint_results)
            with tempfile.NamedTemporaryFile(
                mode="w",
                suffix=".json",
                delete=False,
                encoding="utf-8",
            ) as tmp:
                json.dump(coverage, tmp)
                coverage_json = Path(tmp.name)

        if coverage_json is not None:
            run(
                [
                    sys.executable,
                    "scripts/generate_home_stats.py",
                    "--coverage-json",
                    str(coverage_json),
                ],
                "Update home-stats from graph + lint coverage",
            )
        else:
            run([sys.executable, "scripts/generate_home_stats.py"], "Update home-stats")
    finally:
        if coverage_json is not None:
            coverage_json.unlink(missing_ok=True)

    run([sys.executable, "scripts/graph_exports_sync.py"], "Copy graph exports to docs/exports")

    if not args.skip_quality:
        import lint_wiki

        assert lint_results is not None
        run([sys.executable, "scripts/eval_search_quality.py"], "Run search regression")
        print(lint_wiki.format_report(lint_results))
        failing = lint_wiki._failing_total(lint_results)
        info = lint_wiki._info_total(lint_results)
        if failing == 0:
            if info:
                print(f"✅ 所有检查通过！（另含 {info} 条信息型预警，不阻塞 CI）")
            else:
                print("✅ 所有检查通过！")
        else:
            print(f"⚠️  共发现 {failing} 个问题，请参考上方报告处理。")
        report_path = lint_wiki.save_lint_report(lint_results)
        print(f"\n已将健康报告保存到 {report_path}")
        if failing > 0:
            sys.exit(1)
        run([sys.executable, "scripts/check_export_quality.py"], "Check export consistency")

    if args.check_generated_clean:
        check_generated_clean()

    print("\nPreflight complete.", flush=True)


if __name__ == "__main__":
    main()
