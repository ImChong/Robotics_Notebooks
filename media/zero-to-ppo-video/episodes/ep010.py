# 字幕里的数字写成 $…$（同 008、009）：第几集、第几季、几个数、几个关节；「这一集」「下一集」「一步」「一圈」「一小步」「一个点」这类当量词、
# 指代用的「一」和「三维」照常写汉字。只改字幕，旁白照念
import re as _re

_CN = {"零": 0, "一": 1, "二": 2, "两": 2, "三": 3, "四": 4, "五": 5, "六": 6, "七": 7, "八": 8, "九": 9}


def _int(s):
    if "十" in s:
        a, b = s.split("十")
        return (_CN[a] if a else 1) * 10 + (_CN[b] if b else 0)
    return _CN[s]


def math_subs(s):
    s = _re.sub(r"(?<=第)([一二三四五六七八九十]+)(?=集|季)", lambda m: "$%d$" % _int(m.group(1)), s)
    s = _re.sub(r"(?<![这下后另同某那第])([零一二两三四五六七八九十]+)(?=个数|个关节)", lambda m: "$%d$" % _int(m.group(1)), s)
    # 公式和汉字之间留一个空格（标点旁不留）；字幕先换写法再切行、每行再换一遍，换两遍结果不变
    parts = _re.split(r"(\$[^$]+\$)", s)
    for k, p in enumerate(parts):
        if p.startswith("$") and len(p) > 1:
            if k > 0 and parts[k - 1] and _re.match(r"[一-鿿]", parts[k - 1][-1]):
                parts[k - 1] += " "
            if k + 1 < len(parts) and parts[k + 1] and _re.match(r"[一-鿿]", parts[k + 1][0]):
                parts[k + 1] = " " + parts[k + 1]
    return "".join(parts)


